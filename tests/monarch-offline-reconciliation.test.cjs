const assert=require("node:assert/strict");
const fs=require("node:fs"),vm=require("node:vm");
const source=fs.readFileSync("shared/monarch-offline-reconciliation.js","utf8");
const sandbox={};vm.runInNewContext(source,sandbox);
const api=sandbox.MonarchOfflineLab;assert.ok(api);
const q=api.makeQueue({tenant:"tenant_one",clock:()=>"2026-11-12T12:00:00.000Z"});
const cmd={caseId:"CASE_01",key:"cmd-01",action:"PAYMENT_REQUEST",expectedRevision:1,amountMinor:250000,currency:"NGN"};
assert.equal(q.enqueue(cmd).record.status,"QUEUED_UNVERIFIED");
assert.equal(q.enqueue(cmd).duplicate,true);
assert.throws(()=>q.enqueue({...cmd,amountMinor:999}),/conflict/i);
const ledgerSource=fs.readFileSync("shared/monarch-synthetic-ledger.js","utf8"),ls={};vm.runInNewContext(ledgerSource,ls);
const ledger=ls.MonarchSyntheticLedger.makeLedger({tenant:"tenant_one"});
ledger.register("CASE_01");
assert.equal(q.rehearse("CASE_01","cmd-01",ledger).record.status,"RESOLVED_SIM");
assert.equal(q.rehearse("CASE_01","cmd-01",ledger).duplicate,true);
const q2=api.makeQueue({tenant:"tenant_one"});
q2.enqueue({...cmd,key:"cmd-02",action:"PAYMENT_CONFIRM"});
q2.markUnknown("CASE_01","cmd-02","Network dropped after submission");
assert.throws(()=>q2.rehearse("CASE_01","cmd-02",ledger),/automatic replay prohibited/);
assert.equal(q2.cancel("CASE_01","cmd-02").status,"CANCELLED");
const q3=api.makeQueue({tenant:"tenant_one"});
q3.enqueue({...cmd,key:"cmd-03",action:"FULFILMENT_START"});
assert.throws(()=>q3.rehearse("CASE_01","cmd-03",ledger),/human simulation reconciliation/);
const q4=api.makeQueue({tenant:"tenant_one"});
q4.enqueue(cmd);const archive=q4.exportUntrusted();
assert.equal(q4.inspectUntrustedArchive(archive)[0].status,"QUARANTINED_UNTRUSTED");
assert.throws(()=>q4.inspectUntrustedArchive(archive.replace("tenant_one","tenant_two")),/Wrong tenant/);
assert.equal(q.release,"HOLD");
console.log("PASS: offline queue dedup, conflicting intent, simulation, unknown-outcome no-replay, cancel, high-risk human gate, untrusted archive quarantine, tenant check and HOLD");
