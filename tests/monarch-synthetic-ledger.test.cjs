const assert=require("node:assert/strict");
const fs=require("node:fs"),vm=require("node:vm");
const source=fs.readFileSync("shared/monarch-synthetic-ledger.js","utf8");
const sandbox={};vm.runInNewContext(source,sandbox);
const api=sandbox.MonarchSyntheticLedger;
assert.ok(api);
const a=api.makeLedger({tenant:"tenant_one",clock:()=>"2026-11-12T12:00:00.000Z"});
const b=api.makeLedger({tenant:"tenant_two"});
a.register("CASE_01");
const base={caseId:"CASE_01",simulationAcknowledgement:"SYNTHETIC_ONLY",currency:"NGN"};
const p=a.execute({...base,action:"PAYMENT_REQUEST",key:"pay-1",expectedRevision:1,amountMinor:100000});
assert.equal(p.payment,"PENDING_SIM");
assert.equal(a.execute({...base,action:"PAYMENT_REQUEST",key:"pay-1",expectedRevision:1,amountMinor:100000}).duplicate,true);
assert.throws(()=>a.execute({...base,action:"PAYMENT_REQUEST",key:"pay-1",expectedRevision:2,amountMinor:200000}),/Idempotency key conflict/);
assert.throws(()=>a.execute({...base,action:"PAYMENT_CONFIRM",key:"pay-2",expectedRevision:1,amountMinor:100000}),/Stale case revision/);
const paid=a.execute({...base,action:"PAYMENT_CONFIRM",key:"pay-2",expectedRevision:2,amountMinor:100000});
assert.equal(paid.payment,"PAID_SIM");
const delivery=a.execute({...base,action:"FULFILMENT_START",key:"ful-1",expectedRevision:3});
assert.equal(delivery.fulfilment,"STARTED_SIM");
assert.throws(()=>a.execute({...base,action:"FULFILMENT_START",key:"ful-2",expectedRevision:4}),/cannot be duplicated/);
const pod=a.execute({...base,action:"POD_RECORD",key:"pod-1",expectedRevision:4});
assert.equal(pod.fulfilment,"POD_SIM");
assert.throws(()=>a.execute({...base,action:"REFUND_REQUEST",key:"refund-1",expectedRevision:5,amountMinor:100000}),/Refund not eligible/);
a.register("CASE_02");
assert.throws(()=>a.execute({...base,action:"PAYMENT_REQUEST",key:"xx",expectedRevision:1,amountMinor:0}),/Positive amount/);
assert.throws(()=>a.execute({...base,action:"PAYMENT_REQUEST",key:"xx",expectedRevision:1,amountMinor:10}),/Case not found/);
assert.throws(()=>a.execute({...base,action:"PAYMENT_REQUEST",key:"xx",expectedRevision:1,amountMinor:10,simulationAcknowledgement:"owner"}),/Synthetic-only/);
assert.equal(b.evidence().length,0);
a.stop("CASE_02");
assert.throws(()=>a.execute({...base,caseId:"CASE_02",action:"PAYMENT_REQUEST",key:"stop",expectedRevision:2,amountMinor:100}),/STOPPED/);
assert.equal(a.view("CASE_01").release,"HOLD");
assert.equal(a.evidence("CASE_01").every(x=>x.status==="SYNTHETIC_ONLY"||x.status==="REGISTERED"||x.status==="STOPPED"),true);
console.log("PASS: idempotency, conflicts, stale revision, payment sequence, duplicate fulfilment, POD order, refund protection, zero amount, tenant isolation, acknowledgement, stop gate and permanent HOLD");
