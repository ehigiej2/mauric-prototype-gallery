const assert=require("node:assert/strict");
const fs=require("node:fs"),vm=require("node:vm");
const source=fs.readFileSync("shared/monarch-control-engine.js","utf8");
const sandbox={window:{},document:undefined,Date,Math,Error,Object,Map,String,RegExp};vm.runInNewContext(source,sandbox);
const api=sandbox.window.MonarchControl;
assert.ok(api,"global engine exported");
const a=api.makeEngine({tenant:"tenant_one",prototype:"trade",clock:()=>"2026-11-11T00:00:00Z"});
const b=api.makeEngine({tenant:"tenant_two",prototype:"waka"});
a.create("CASE_01");
assert.throws(()=>a.create("CASE_01"),/duplicate/i);
assert.throws(()=>a.transition("CASE_01","APPROVED_FOR_SIMULATION",{actor:"owner"}),/Invalid state/);
for(const key of api.REQUIRED)a.record("CASE_01",key,"REVIEWED_UNAUTHENTICATED");
a.transition("CASE_01","RESEARCH");
a.transition("CASE_01","EVIDENCE_REVIEW");
a.transition("CASE_01","OWNER_REVIEW");
assert.throws(()=>a.transition("CASE_01","APPROVED_FOR_SIMULATION",{actor:"researcher"}),/Owner required/);
a.transition("CASE_01","APPROVED_FOR_SIMULATION",{actor:"owner"});
a.transition("CASE_01","FULFILMENT_SIMULATED");
a.revokeConsent("CASE_01");
assert.equal(a.view("CASE_01").status,"EVIDENCE_REVIEW");
assert.equal(a.view("CASE_01").approvedBy,null);
const packet=a.handoff("CASE_01","waka");
assert.throws(()=>b.receive(packet),/cross-tenant/);
const sameTenant=api.makeEngine({tenant:"tenant_one",prototype:"waka"});
const received=sameTenant.receive(packet);
assert.equal(received.duplicate,false);
assert.equal(received.case.status,"REQUEST");
assert.equal(sameTenant.receive(packet).duplicate,true);
a.transition("CASE_01","STOPPED",{reason:"test stop"});
assert.throws(()=>a.transition("CASE_01","RESEARCH"),/Stopped case/);
assert.throws(()=>a.record("CASE_01","supplier","SUPPLIED_UNVERIFIED"),/STOPPED/);
console.log("PASS: tenant isolation, duplicate prevention, ordered transitions, owner gate, consent revocation, quarantined handoff and immutable stop");
